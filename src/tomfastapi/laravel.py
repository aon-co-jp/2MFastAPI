"""Laravel routes (routes/web.php, routes/api.php) -> FastAPI/MFastAPI-compatible Python.

Only simple closures are translated:
  return 'text';  /  return 'Hello ' . $name;  /  return ['k' => 'v', 'id' => $id];
Anything else becomes a route that answers 501 with a TODO comment holding the original PHP.
"""
from __future__ import annotations

import os
import re
from typing import List, Optional, Tuple

_ROUTE = re.compile(
    r"Route::(get|post|put|patch|delete)\s*\(\s*(['\"])(.*?)\2\s*,\s*function\s*\(([^)]*)\)\s*(?:use\s*\([^)]*\)\s*)?\{",
    re.S)


def _body(src: str, start: int) -> Tuple[str, int]:
    depth, i, q = 1, start, None
    while i < len(src):
        c = src[i]
        if q:
            if c == "\\":
                i += 1
            elif c == q:
                q = None
        elif c in "'\"":
            q = c
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return src[start:i], i + 1
        i += 1
    return src[start:], len(src)


def _str(tok: str) -> Optional[str]:
    tok = tok.strip()
    if len(tok) >= 2 and tok[0] == tok[-1] == "'":
        inner = tok[1:-1]
        if "'" in inner.replace("\\'", ""):
            return None
        return repr(inner.replace("\\'", "'").replace("\\\\", "\\"))
    if len(tok) >= 2 and tok[0] == tok[-1] == '"':
        inner = tok[1:-1]
        if "$" in inner or '"' in inner.replace('\\"', ""):
            return None  # string interpolation is not translated
        return repr(inner.replace('\\"', '"'))
    return None


def _split(s: str, sep: str) -> Optional[List[str]]:
    out, cur, q, depth = [], "", None, 0
    for c in s:
        if q:
            cur += c
            if c == q:
                q = None
            continue
        if c in "'\"":
            q = c
        elif c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
        if c == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += c
    if q:
        return None
    out.append(cur)
    return out


def _expr(e: str, params: List[str]) -> Optional[str]:
    e = e.strip()
    if e.startswith("[") and e.endswith("]"):
        items = _split(e[1:-1], ",")
        if items is None:
            return None
        pairs = []
        for it in items:
            if not it.strip():
                continue
            kv = it.split("=>", 1)
            if len(kv) != 2:
                return None
            k, v = _str(kv[0]), _expr(kv[1], params)
            if k is None or v is None:
                return None
            pairs.append("%s: %s" % (k, v))
        return "{" + ", ".join(pairs) + "}"
    parts = _split(e, ".")
    if parts is None:
        return None
    if len(parts) > 1:
        conv = []
        for p in parts:
            x = _expr(p, params)
            if x is None or x.startswith("{"):
                return None
            conv.append(x if x[0] in "'\"" else "str(%s)" % x)
        return " + ".join(conv)
    m = re.fullmatch(r"\$(\w+)", e)
    if m:
        return m.group(1) if m.group(1) in params else None
    if re.fullmatch(r"-?\d+(\.\d+)?", e):
        return e
    return _str(e)


def translate(php: str) -> Tuple[str, int, int]:
    """Return (python source, translated count, TODO count)."""
    lines = ["# generated by 2mfastapi laravel: FastAPI / MFastAPI compatible",
             "from fastapi import FastAPI",
             "from fastapi.responses import JSONResponse, PlainTextResponse", "",
             "app = FastAPI()", ""]
    ok = todo = n = pos = 0
    while True:
        m = _ROUTE.search(php, pos)
        if not m:
            break
        verb, path, args = m.group(1), m.group(3), m.group(4)
        body, pos = _body(php, m.end())
        n += 1
        url = re.sub(r"\{(\w+)\?\}", r"{\1}", "/" + path.strip("/"))
        params = re.findall(r"\{(\w+)\}", url)
        arg_names = [a.strip().split()[-1].lstrip("$") for a in args.split(",") if a.strip()]
        py_body = None
        rm = re.fullmatch(r"\s*return\s+(.*?);\s*", body, re.S)
        if rm and len(arg_names) <= len(params):
            expr = rm.group(1)
            # Laravel binds route segments to closure arguments by position
            for a, p in zip(arg_names, params):
                expr = re.sub(r"\$%s\b" % re.escape(a), "$" + p, expr)
            py = _expr(expr, params)
            if py is not None:
                kind = "JSONResponse" if py.startswith("{") else "PlainTextResponse"
                py_body = "    return %s(%s)" % (kind, py)
        lines.append('@app.%s("%s")' % (verb, url))
        lines.append("def route_%d(%s):" % (n, ", ".join("%s: str" % p for p in params)))
        if py_body:
            ok += 1
            lines.append(py_body)
        else:
            todo += 1
            lines.append("    # TODO(2mfastapi): not translated automatically. Original PHP:")
            for l in body.strip().splitlines():
                lines.append("    #   " + l.rstrip())
            lines.append('    return JSONResponse({"detail": "Not Implemented (converted from Laravel)"}, status_code=501)')
        lines.append("")
    return "\n".join(lines), ok, todo


def convert_laravel(root: str, out_dir: str) -> Tuple[int, int]:
    """Translate routes/web.php and routes/api.php (api.php routes get the /api prefix, as in Laravel)."""
    os.makedirs(out_dir, exist_ok=True)
    srcs = []
    for fn, prefix in (("web.php", False), ("api.php", True)):
        p = os.path.join(root, "routes", fn)
        if os.path.isfile(p):
            with open(p, encoding="utf-8") as fh:
                php = fh.read()
            if prefix:
                php = re.sub(r"(Route::\w+\s*\(\s*)(['\"])/?", lambda m: m.group(1) + m.group(2) + "api/", php)
            srcs.append(php)
    code, ok, todo = translate("\n".join(srcs))
    with open(os.path.join(out_dir, "main.py"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(code)
    return ok, todo
